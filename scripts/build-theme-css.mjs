import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const tokens = require('../lib/design/tokens.js');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const defaultFile = path.join(root, 'global.css');
const GENERATED_START = '/* design tokens: generated by npm run tokens */';
const GENERATED_END = '/* end design tokens */';

function kebabCase(value) {
  return value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

function colorValue(value) {
  if (value.startsWith('#')) {
    const hex = value.slice(1);
    const expanded = hex.length === 3 ? [...hex].map((part) => `${part}${part}`).join('') : hex;
    const number = Number.parseInt(expanded, 16);
    return `${number >> 16} ${(number >> 8) & 255} ${number & 255}`;
  }
  const match = value.match(/^rgba?\((\d+),\s*(\d+),\s*(\d+)(?:,\s*([\d.]+))?\)$/);
  if (match) return `${match[1]} ${match[2]} ${match[3]}${match[4] ? ` / ${match[4]}` : ''}`;
  throw new Error(`Unsupported color token: ${value}`);
}

function renderMode(scheme) {
  const mode = tokens.colors[scheme];
  const lines = Object.entries(mode).map(([name, value]) => `    --color-${kebabCase(name)}: ${colorValue(value)};`);
  Object.entries(tokens.radius).forEach(([name, value]) => lines.push(`    --radius-${name}: ${value}px;`));
  Object.entries(tokens.motion.durations).forEach(([name, value]) => lines.push(`    --motion-duration-${name}: ${value}ms;`));
  return `${scheme === 'light' ? ':root' : '.dark:root'} {\n${lines.join('\n')}\n  }`;
}

export function renderThemeCss() {
  return `${GENERATED_START}\n  ${renderMode('light')}\n\n  ${renderMode('dark')}\n  ${GENERATED_END}`;
}

function withGeneratedBlock(source) {
  const block = renderThemeCss();
  const marked = new RegExp(`${GENERATED_START}[\\s\\S]*?${GENERATED_END}`);
  if (marked.test(source)) return source.replace(marked, block);
  const legacyBase = /@layer base \{[\s\S]*?\n\}/;
  if (!legacyBase.test(source)) throw new Error('Could not find the @layer base block in global.css');
  return source.replace(legacyBase, `@layer base {\n  ${block}\n}`);
}

function parseArgs() {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const print = args.includes('--print');
  const fileIndex = args.indexOf('--file');
  const file = fileIndex >= 0 ? path.resolve(args[fileIndex + 1]) : defaultFile;
  return { check, file, print };
}

const { check, file, print } = parseArgs();
const current = readFileSync(file, 'utf8');
const generated = withGeneratedBlock(current);

if (print) {
  process.stdout.write(renderThemeCss());
} else if (check) {
  if (generated !== current) {
    console.error(`${path.relative(root, file)} is out of date. Run npm run tokens.`);
    process.exitCode = 1;
  }
} else if (generated !== current) {
  writeFileSync(file, generated);
}
